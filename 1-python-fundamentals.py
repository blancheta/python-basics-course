# A CONSTANT is a container whose the value does not change
DB_PASSWORD = "1234"

# DB_PASSWORD = "4567"

# A variable is a container whose the value can change
message = "Hello"

print("Welcome!")
print(message)

# Integer: int
age = 20
print(age)

# Decimal: float
price = 19.99
print(price)

# Boolean: bool True or False
is_verified = True
print(is_verified)